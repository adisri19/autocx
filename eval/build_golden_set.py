def generate_golden_set(output_file: Path = GOLDEN_SET_FILE) -> List[Dict[str, Any]]:
    """Build, validate, and write the 200-example stratified golden dataset."""
    golden_examples = []
    example_id = 1

    for intent in INTENT_LABELS:
        seeds = INTENT_SEED_DATA.get(intent, [])
        if len(seeds) < 25:
            logger.warning(f"Intent {intent} has fewer than 25 examples ({len(seeds)})")

        for msg, expected_esc, notes in seeds[:25]:
            golden_examples.append({
                "id": example_id,
                "message": msg,
                "true_intent": intent,
                "expected_escalation": bool(expected_esc),
                "notes": notes,
            })
            example_id += 1

    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, "w", encoding="utf-8") as f:
        for ex in golden_examples:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")

    logger.info(f"Successfully created golden set with {len(golden_examples)} examples at {output_file}")
    return golden_examples


